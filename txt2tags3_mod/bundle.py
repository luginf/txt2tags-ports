#!/usr/bin/env python3
"""Build a single-file, self-contained txt2tags.py from the modular package.

Usage (from anywhere):
    python3 txt2tags3_mod/bundle.py            # writes txt2tags3_mod/out/txt2tags.py
    python3 txt2tags3_mod/bundle.py OUTFILE    # writes OUTFILE ('-' = stdout)

Technique (same idea as ../txt2tags_perl/bundle.pl): the source of every
module of the package is stored as a string literal, and a meta-path finder
serves them as the package 'txt2tags3_mod'.  Nothing is rewritten, so relative
imports, the shared 'state' module, lazy imports inside functions and circular
imports behave exactly as in the modular layout.  The generated file runs
__main__.py's code as '__main__'.

bundle.py itself is not part of the bundle.  The 'targets/' sub-directory is
not bundled either: constants.py only does a top-level 'import targets' (not
a relative one), which is optional there and never resolves to it.
"""

import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PACKAGE = os.path.basename(HERE)  # txt2tags3_mod
DEFAULT_OUT = os.path.join(HERE, "out", "txt2tags.py")
SKIP = {"bundle.py"}

TEMPLATE = '''\
#!/usr/bin/env python3
# txt2tags - convert plain text to 40+ markup formats
# Single-file bundle of the "%(pkg)s" package, generated by bundle.py.
# DO NOT EDIT: edit the modules and run  python3 %(pkg)s/bundle.py
#
# Run:  python3 txt2tags.py -t html input.t2t

import importlib.abc
import importlib.util
import sys

_PACKAGE = %(pkg)r

_SOURCES = {
%(sources)s}


class _BundleLoader(importlib.abc.Loader):
    def __init__(self, name):
        self.name = name

    def _key(self):
        return self.name[len(_PACKAGE) + 1:] or "__init__"

    def create_module(self, spec):
        return None

    def get_source(self, fullname):
        return _SOURCES[self._key()]

    def exec_module(self, module):
        key = self._key()
        module.__file__ = "<%%s/%%s.py>" %% (_PACKAGE, key)
        code = compile(_SOURCES[key], module.__file__, "exec")
        exec(code, module.__dict__)


class _BundleFinder(importlib.abc.MetaPathFinder):
    def find_spec(self, fullname, path=None, target=None):
        if fullname == _PACKAGE:
            key = "__init__"
        elif fullname.startswith(_PACKAGE + "."):
            key = fullname[len(_PACKAGE) + 1:]
        else:
            return None
        if key not in _SOURCES or (key == "__main__" and fullname != _PACKAGE + ".__main__"):
            return None
        spec = importlib.util.spec_from_loader(
            fullname, _BundleLoader(fullname), is_package=(key == "__init__")
        )
        return spec


def _run():
    sys.meta_path.insert(0, _BundleFinder())
    package = importlib.import_module(_PACKAGE)
    filename = "<%%s/__main__.py>" %% _PACKAGE
    namespace = {
        "__name__": "__main__",
        "__package__": _PACKAGE,
        "__file__": filename,
        "__loader__": package.__loader__,
    }
    exec(compile(_SOURCES["__main__"], filename, "exec"), namespace)


if __name__ == "__main__":
    _run()
'''


def literal(source):
    """A Python literal for `source`: readable raw string if safe, else repr()."""
    raw = "r'''" + source + "'''"
    if "'''" not in source and not source.endswith(("\\", "'")) and "\r" not in source:
        try:
            if ast.literal_eval(raw) == source:
                return raw
        except SyntaxError:
            pass
    return repr(source)


def build():
    names = sorted(
        f for f in os.listdir(HERE) if f.endswith(".py") and f not in SKIP
    )
    entries = []
    for fname in names:
        with open(os.path.join(HERE, fname), encoding="utf-8", newline="") as fh:
            source = fh.read()
        compile(source, fname, "exec")  # fail early on a syntax error
        key = fname[:-3]
        lit = literal(source)
        assert ast.literal_eval(lit) == source
        entries.append("    %r: %s,\n" % (key, lit))
    return TEMPLATE % {"pkg": PACKAGE, "sources": "".join(entries)}


def main(argv):
    text = build()
    out = argv[1] if len(argv) > 1 else DEFAULT_OUT
    if out == "-":
        sys.stdout.write(text)
        return
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)
    os.chmod(out, 0o755)
    print("wrote %s (%d bytes)" % (out, len(text.encode("utf-8"))), file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv)
