#!/usr/bin/env perl
# bundle.pl — produce a single self-contained txt2tags.pl
# Usage:
#   perl bundle.pl            # writes txt2tags_perl/out/txt2tags.pl
#   perl bundle.pl FILE       # writes FILE ('-' = stdout)
#
# Technique: App::FatPacker approach — each module source is stored as a
# string literal; a @INC hook intercepts "use Module" calls at compile time
# and serves those strings.  This preserves normal Exporter semantics.

use strict;
use warnings;
use FindBin qw($RealBin);
use File::Spec;
use File::Path qw(make_path);
use File::Basename qw(dirname);

# Output target (resolved before chdir so a relative FILE is relative to the caller)
my $outfile = @ARGV ? shift @ARGV : File::Spec->catfile($RealBin, 'out', 'txt2tags.pl');
$outfile = File::Spec->rel2abs($outfile) unless $outfile eq '-';
chdir $RealBin or die "Cannot chdir to $RealBin: $!";

sub slurp {
    my ($file) = @_;
    open my $fh, '<', $file or die "Cannot read $file: $!";
    local $/;
    my $content = <$fh>;
    close $fh;
    return $content;
}

# Dependency order (each module may use the ones above it)
my @modules = (
    [ 'Text/Txt2tags/Constants.pm' => 'lib/Text/Txt2tags/Constants.pm' ],
    [ 'Text/Txt2tags/State.pm'     => 'lib/Text/Txt2tags/State.pm'     ],
    [ 'Text/Txt2tags/Utils.pm'     => 'lib/Text/Txt2tags/Utils.pm'     ],
    [ 'Text/Txt2tags/Regexes.pm'   => 'lib/Text/Txt2tags/Regexes.pm'   ],
    [ 'Text/Txt2tags/Tags.pm'      => 'lib/Text/Txt2tags/Tags.pm'      ],
    [ 'Text/Txt2tags/Rules.pm'     => 'lib/Text/Txt2tags/Rules.pm'     ],
    [ 'Text/Txt2tags/Config.pm'    => 'lib/Text/Txt2tags/Config.pm'    ],
    [ 'Text/Txt2tags/Processing.pm'=> 'lib/Text/Txt2tags/Processing.pm'],
    [ 'Text/Txt2tags/Output.pm'    => 'lib/Text/Txt2tags/Output.pm'    ],
    [ 'Text/Txt2tags/Converter.pm' => 'lib/Text/Txt2tags/Converter.pm' ],
    [ 'Text/Txt2tags.pm'           => 'lib/Text/Txt2tags.pm'           ],
);

# Choose a heredoc delimiter that won't appear in any module source
my $DELIM = 'END_OF_MODULE_SOURCE';

if ($outfile ne '-') {
    make_path(dirname($outfile));
    open my $ofh, '>', $outfile or die "Cannot write $outfile: $!";
    select $ofh;
}

print <<'PREAMBLE';
#!/usr/bin/env perl
# txt2tags - convert plain text to 40+ markup formats
# Single-file bundle — generated by bundle.pl
# Run:  perl txt2tags.pl -t html input.t2t
# =======================================================================

use strict;
use warnings;

# -----------------------------------------------------------------------
# @INC hook (App::FatPacker technique): serve bundled modules from strings
# -----------------------------------------------------------------------
BEGIN {
    my %_bundled;
PREAMBLE

for my $entry (@modules) {
    my ($key, $file) = @$entry;
    my $source = slurp($file);
    # Escape any END_OF_MODULE_SOURCE that might appear inside the source
    $source =~ s/\Q$DELIM\E/${DELIM}_/g;
    print "    \$_bundled{'$key'} = <<'$DELIM';\n";
    print $source;
    print "\n$DELIM\n";
}

print <<'HOOK';
    unshift @INC, sub {
        my (undef, $file) = @_;
        return unless exists $_bundled{$file};
        my $src = $_bundled{$file};
        open my $fh, '<', \$src or die "Cannot open in-memory module $file: $!";
        return $fh;
    };
}

# -----------------------------------------------------------------------
# Entry point (bin/txt2tags)
# -----------------------------------------------------------------------
HOOK

my $cli = slurp('bin/txt2tags');
$cli =~ s/\A#!.*\n//;       # shebang
$cli =~ s/^use FindBin[^\n]*\n//mg;
$cli =~ s/^use lib[^\n]*\n//mg;
print $cli;

if ($outfile ne '-') {
    close select(STDOUT);
    chmod 0755, $outfile;
    print STDERR "wrote $outfile\n";
}
